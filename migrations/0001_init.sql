CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE COLLATE NOCASE,
 email TEXT NOT NULL UNIQUE COLLATE NOCASE, password_hash TEXT NOT NULL,
 password_salt TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at INTEGER NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions(user_id);
CREATE TABLE IF NOT EXISTS pantry (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL, amount REAL, unit TEXT, approximate INTEGER NOT NULL DEFAULT 0,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,name)
);
CREATE TABLE IF NOT EXISTS saved_recipes (
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 recipe_id TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,recipe_id)
);
CREATE TABLE IF NOT EXISTS recipe_notes (
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 recipe_id TEXT NOT NULL, ingredient_name TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
 PRIMARY KEY(user_id,recipe_id,ingredient_name)
);
CREATE TABLE IF NOT EXISTS preferences (
 user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 exclusions TEXT NOT NULL DEFAULT '[]'
);
